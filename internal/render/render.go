// Package render writes the import blocks and the match report.
package render

import (
	"encoding/json"
	"fmt"
	"strings"
	"text/tabwriter"

	"github.com/moveeeax/tf-import-block-gen/internal/match"
)

// ImportBlocks renders Terraform 1.5 import blocks for every confident match.
// A block whose id format could not be verified keeps a comment above it so
// the output stays usable without being silently wrong.
func ImportBlocks(o match.Outcome) string {
	var b strings.Builder
	b.WriteString("# Generated by tf-import-block-gen. Review before `terraform apply`.\n")
	if len(o.Matched) == 0 {
		b.WriteString("# No confident matches.\n")
		return b.String()
	}
	for _, m := range o.Matched {
		b.WriteString("\n")
		if !m.Verified {
			fmt.Fprintf(&b, "# %s\n", m.Note)
		}
		if m.Rule == match.RuleOverride {
			b.WriteString("# matched by --map override\n")
		}
		b.WriteString("import {\n")
		fmt.Fprintf(&b, "  to = %s\n", m.Address)
		fmt.Fprintf(&b, "  id = %q\n", m.ID)
		b.WriteString("}\n")
	}
	return b.String()
}

// ReportTable renders the human-readable report.
func ReportTable(o match.Outcome) string {
	var b strings.Builder
	section := func(title string, n int, rows func(w *tabwriter.Writer)) {
		fmt.Fprintf(&b, "%s (%d)\n", title, n)
		if n == 0 {
			b.WriteString("  -\n\n")
			return
		}
		w := tabwriter.NewWriter(&b, 0, 2, 2, ' ', 0)
		rows(w)
		w.Flush()
		b.WriteString("\n")
	}

	section("MATCHED", len(o.Matched), func(w *tabwriter.Writer) {
		for _, m := range o.Matched {
			flag := ""
			if !m.Verified {
				flag = "\tid format unverified"
			}
			fmt.Fprintf(w, "  %s\t%s\tvia %s%s\n", m.Address, m.ID, m.Rule, flag)
		}
	})
	section("AMBIGUOUS", len(o.Ambiguous), func(w *tabwriter.Writer) {
		for _, a := range o.Ambiguous {
			fmt.Fprintf(w, "  %s\t%s\tcandidates: %s\n", a.Address, a.PlannedName, strings.Join(a.Candidates, ", "))
		}
	})
	section("NEW", len(o.New), func(w *tabwriter.Writer) {
		for _, n := range o.New {
			fmt.Fprintf(w, "  %s\t%s\tno live candidate\n", n.Address, n.PlannedName)
		}
	})
	section("UNMANAGED", len(o.Unmanaged), func(w *tabwriter.Writer) {
		for _, u := range o.Unmanaged {
			fmt.Fprintf(w, "  %s\t%s\t%s\n", u.Type, u.Name, u.ID)
		}
	})

	fmt.Fprintf(&b, "%d matched, %d ambiguous, %d new, %d unmanaged\n",
		len(o.Matched), len(o.Ambiguous), len(o.New), len(o.Unmanaged))
	return b.String()
}

type summary struct {
	Matched   int `json:"matched"`
	Ambiguous int `json:"ambiguous"`
	New       int `json:"new"`
	Unmanaged int `json:"unmanaged"`
}

type reportJSON struct {
	Matched   []match.Matched   `json:"matched"`
	Ambiguous []match.Ambiguous `json:"ambiguous"`
	New       []match.New       `json:"new"`
	Unmanaged []match.Unmanaged `json:"unmanaged"`
	Summary   summary           `json:"summary"`
}

// ReportJSON renders the machine-readable report.
func ReportJSON(o match.Outcome) (string, error) {
	r := reportJSON{
		Matched:   nonNilMatched(o.Matched),
		Ambiguous: nonNilAmbiguous(o.Ambiguous),
		New:       nonNilNew(o.New),
		Unmanaged: nonNilUnmanaged(o.Unmanaged),
		Summary: summary{
			Matched:   len(o.Matched),
			Ambiguous: len(o.Ambiguous),
			New:       len(o.New),
			Unmanaged: len(o.Unmanaged),
		},
	}
	raw, err := json.MarshalIndent(r, "", "  ")
	if err != nil {
		return "", err
	}
	return string(raw) + "\n", nil
}

func nonNilMatched(v []match.Matched) []match.Matched {
	if v == nil {
		return []match.Matched{}
	}
	return v
}

func nonNilAmbiguous(v []match.Ambiguous) []match.Ambiguous {
	if v == nil {
		return []match.Ambiguous{}
	}
	return v
}

func nonNilNew(v []match.New) []match.New {
	if v == nil {
		return []match.New{}
	}
	return v
}

func nonNilUnmanaged(v []match.Unmanaged) []match.Unmanaged {
	if v == nil {
		return []match.Unmanaged{}
	}
	return v
}
